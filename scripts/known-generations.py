#!/usr/bin/env python3
"""Rebuild patches/homebridge-plugin/known-generations.txt from this repo's git history.

    python3 scripts/known-generations.py STOCK_DIR [--repo DIR] [--check]

STOCK_DIR is an unpacked stock plugin tarball (the directory holding package.json), e.g.
    curl -fsSLO https://registry.npmjs.org/homebridge-google-nest-sdm/-/homebridge-google-nest-sdm-1.1.25.tgz
    tar xzf homebridge-google-nest-sdm-1.1.25.tgz        # -> ./package

For every version of every patch file in git history (plus the working-tree copy), this
applies it to a fresh copy of the stock target and records the SHA-256 of the result, when
it applies cleanly. apply-snapshot-patch.sh treats a target whose hash is listed as a file
this repo patched, so it may restore that file from stock and apply the current patch. A
target with any other content is refused. Run this after re-cutting a patch, and commit the
result; --check exits 1 if the file on disk is out of date instead of writing it.

It needs the full history (a shallow clone would see only the newest version of each patch)
and refuses to run in a shallow clone. Entries already in the file are kept even when this
run does not regenerate them, so an entry is never dropped: dropping one would make every
install still carrying that generation refuse to upgrade.

Generations cut for another plugin version simply do not apply to this stock and are left
out, so the list only ever names files that came from this stock version.
"""
import argparse, hashlib, json, os, re, shutil, subprocess, sys, tempfile

PATCHES = {  # patch file -> target, as in apply-snapshot-patch.sh
    "Camera.js.patch": "dist/sdm/Camera.js",
    "Api.js.patch": "dist/sdm/Api.js",
    "StreamingDelegate.js.patch": "dist/StreamingDelegate.js",
    "HksvStreamer.js.patch": "dist/HksvStreamer.js",
    "config.schema.json.patch": "config.schema.json",
}
REL = "patches/homebridge-plugin/"


def git(repo, *args):
    return subprocess.run(["git", "-C", repo, *args], check=True, capture_output=True).stdout


def generations(repo, pf):
    """[(label, patch bytes)] for every committed version of pf, oldest first, plus the working tree."""
    out = []
    for c in git(repo, "log", "--reverse", "--format=%h", "--", REL + pf).decode().split():
        try:
            out.append((c, git(repo, "show", "%s:%s%s" % (c, REL, pf))))
        except subprocess.CalledProcessError:  # the commit that deleted it
            pass
    wt = os.path.join(repo, REL, pf)
    if os.path.exists(wt):
        out.append(("working-tree", open(wt, "rb").read()))
    return out


def patched_hash(stock, target, patch_bytes):
    with tempfile.TemporaryDirectory() as td:
        dst = os.path.join(td, target)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy(os.path.join(stock, target), dst)
        r = subprocess.run(["patch", "-p1", "-d", td, "--force", "--batch", "--fuzz=0", "--no-backup-if-mismatch", "-s"],
                           input=patch_bytes, capture_output=True)
        if r.returncode != 0 or os.path.exists(dst + ".rej"):
            return None
        return hashlib.sha256(open(dst, "rb").read()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stock")
    ap.add_argument("--repo", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if git(a.repo, "rev-parse", "--is-shallow-repository").decode().strip() == "true":
        sys.exit("refusing: %s is a shallow clone, so older patch generations are missing "
                 "(run `git fetch --unshallow` first)" % a.repo)
    version = json.load(open(os.path.join(a.stock, "package.json")))["version"]
    lines = ["# SHA-256 of each plugin file as patched by a past or current version of this repo's",
             "# patches, applied to stock homebridge-google-nest-sdm %s." % version,
             "# Generated by scripts/known-generations.py; read by scripts/apply-snapshot-patch.sh.",
             "# <sha256>  <target>  <commit of the patch file>"]
    for pf, target in PATCHES.items():
        seen = set()
        for label, data in generations(a.repo, pf):
            h = patched_hash(a.stock, target, data)
            if h and h not in seen:
                seen.add(h)
                lines.append("%s  %s  %s" % (h, target, label))
    out = os.path.join(a.repo, REL, "known-generations.txt")
    old = open(out).read() if os.path.exists(out) else ""
    have = set(re.findall(r"^([0-9a-f]{64})  (\S+)", "\n".join(lines), re.M))
    for m in re.finditer(r"^([0-9a-f]{64})  (\S+).*$", old, re.M):
        if (m.group(1), m.group(2)) not in have:
            lines.append(m.group(0))  # kept: never drop a generation an install may carry
            have.add((m.group(1), m.group(2)))
    text = "\n".join(lines) + "\n"
    # The working-tree label becomes a commit id once committed; compare hashes and targets only.
    key = lambda t: sorted(re.findall(r"^([0-9a-f]{64})  (\S+)", t, re.M))
    if a.check:
        if key(old) != key(text):  # text includes everything in old, so only a missing entry differs
            print("known-generations.txt is out of date; run without --check")
            sys.exit(1)
        print("known-generations.txt is up to date")
        return
    open(out, "w").write(text)
    print("wrote %d entries to %s" % (len(lines) - 4, out))


if __name__ == "__main__":
    main()
